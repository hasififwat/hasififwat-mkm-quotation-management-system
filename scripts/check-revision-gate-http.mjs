import {guardRevisionManifest} from './helpers/revision-evidence.mjs';
import fs from 'node:fs/promises';
import {ConvexHttpClient} from 'convex/browser';
import assert from 'node:assert/strict';
const p='/private/tmp/mkm-issue61-run';
const run=JSON.parse(await fs.readFile(p+'/run.json','utf8'));
assert.equal(run.owner,'issue-61');assert.equal(run.url,'http://127.0.0.1:13965');
guardRevisionManifest(run,p);
const session=JSON.parse(await fs.readFile(p+'/.session.json','utf8'));
const gate=JSON.parse(await fs.readFile(p+'/gate-ui.json','utf8'));
const c=new ConvexHttpClient(run.url);c.setAuth(session.token);
const a=await c.query('quotationRevisionUi:availability',{});
const headers={'Content-Type':'application/json',Cookie:`__convexAuthJWT=${session.token}; __convexAuthRefreshToken=${session.refreshToken}`};
const save=await fetch('http://localhost:3540/api/quotations/create',{method:'POST',headers,body:JSON.stringify({command:gate.command,expected_actor:a.actor})});
assert.equal(save.status,gate.migration==='done'&&gate.enabled?200:422);
const replay=await fetch('http://localhost:3540/api/quotations/create',{method:'POST',headers,body:JSON.stringify(gate.legacyPayload)});
assert.equal(replay.status,200);const replayed=await replay.json();assert.equal(replayed.id,gate.legacyId);
const result={sourceCommit:run.sourceCommit,id:gate.id,migration:gate.migration,enabled:gate.enabled,mode:a.mode,newCommandStatus:save.status,legacyReplayStatus:replay.status,replay:replayed};
await fs.writeFile(p+'/gate-http-'+gate.id+'.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result));
