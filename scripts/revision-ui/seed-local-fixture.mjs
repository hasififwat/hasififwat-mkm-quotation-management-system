import { readFile, writeFile, chmod } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ConvexHttpClient } from 'convex/browser';
import { randomUUID } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
if (!process.env.REVISION_UI_RUN_DIR) throw new Error('Set REVISION_UI_RUN_DIR to an owned external fixture directory');
const runDir = path.resolve(process.env.REVISION_UI_RUN_DIR);
if (runDir.split(path.sep).includes('.next')) throw new Error('REVISION_UI_RUN_DIR must be outside .next');
const run = JSON.parse(await readFile(path.join(runDir, 'run.json'), 'utf8'));
if (!/^http:\/\/127\.0\.0\.1:[0-9]+$/.test(run.url) || run.owner !== 'quotation-revisions-59') throw new Error('Unexpected verification backend');
const account = JSON.parse(await readFile(run.fixtureAccountPath, 'utf8'));
const { api } = await import(pathToFileURL(path.join(run.sourceDir, 'convex/_generated/api.js')).href);
const { form, normalize } = await import(pathToFileURL(path.join(run.sourceDir, 'scripts/helpers/submission-fixtures.mjs')).href);
const client = new ConvexHttpClient(run.url);
const signedIn = await client.action(api.auth.signIn, { provider: 'password', params: { ...account, flow: 'signUp' } });
if (!signedIn.tokens?.token) throw new Error('Fixture signup did not return a session');
await writeFile(path.join(runDir, '.session.json'), JSON.stringify(signedIn.tokens));
await chmod(path.join(runDir, '.session.json'), 0o600);
client.setAuth(signedIn.tokens.token);
await client.mutation(api.profiles.createProfileForEmail, { email: account.email, fullName: 'Revision Verification', branch: 'Disposable fixture' });
const selectedClient = await client.mutation(api.clients.create, { name: 'Revision History Fixture', phone_number: '' });
const packageResult = await client.mutation(api.packages.createPackage, { payload: normalize({ ...form(), name: 'Revision verification package' }) });
const packages = await client.query(api.packages.listWithRooms, {});
const selectedPackage = packages.find(p => String(p._id) === packageResult.packageDocId);
if (!selectedPackage) throw new Error('Saved fixture package is missing');
const payload = { request_key: randomUUID(), reviewed_context: selectedPackage.creation_context, pic_name: 'Revision Verification', branch: 'Disposable fixture', client_id: selectedClient.id, package_id: String(selectedPackage._id), flight_id: String(selectedPackage.flights[0]._id), selected_rooms: [{ room_type: 'Quad', price: 1200, pax: 4 }], adds_ons: [{ name: 'Airport transfer', price: 100, pax: 4 }], discounts: [{ name: 'Group discount', price: 50, pax: 4 }], notes: 'Baseline saved before immutable revisions.' };
const quotation = await client.mutation(api.quotations.create, { payload });
const reopened = await client.query(api.quotations.getQuotationFullDetails, { target_quotation_id: quotation.id });
if (reopened.total_amount !== 5000) throw new Error('Fixture total did not persist');
const fixture = { backend: run.url, sourceCommit: run.sourceCommit, clientId: selectedClient.id, packageId: String(selectedPackage._id), quotationId: quotation.id, reference: quotation.quotation_number, total: reopened.total_amount, fixtureAccountPath: run.fixtureAccountPath };
await writeFile(path.join(runDir, 'fixture.json'), JSON.stringify(fixture, null, 2));
console.log(JSON.stringify(fixture, null, 2));
