import path from 'node:path';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {verifyRevisionSource,guardRevisionManifest,guardRevisionTarget} from './helpers/revision-evidence.mjs';
import {ConvexHttpClient} from 'convex/browser';
import {createHash} from 'node:crypto';
const runDir='/private/tmp/mkm-issue61-run';
const run=JSON.parse(await fs.readFile(`${runDir}/run.json`,'utf8'));
assert.equal(run.owner,'issue-61');assert.equal(run.url,'http://127.0.0.1:13965');
assert.equal(path.resolve(run.sourceDir),path.join(runDir,'source'));
guardRevisionManifest(run,runDir);
const env=Object.fromEntries((await fs.readFile(`${run.sourceDir}/.env.local`,'utf8')).split('\n').filter(Boolean).map(l=>{const i=l.indexOf('=');return[l.slice(0,i),l.slice(i+1)];}));
guardRevisionTarget(run,runDir,env,run.sourceDir);
const source=await verifyRevisionSource(run);
const session=JSON.parse(await fs.readFile(`${runDir}/.session.json`,'utf8'));
const proof=JSON.parse(await fs.readFile(`${runDir}/backend-proof.json`,'utf8'));
const url=`http://localhost:3540/api/quotations/${proof.pdf.revisionId}/pdf`;
const anonymous=await fetch(url);assert.equal(anonymous.status,401);
const response=await fetch(url,{headers:{Cookie:`__convexAuthJWT=${session.token}; __convexAuthRefreshToken=${session.refreshToken}`}});
assert.equal(response.status,200,`Authenticated route status ${response.status}`);
assert.equal(response.headers.get('content-type'),'application/pdf');
assert.equal(response.headers.get('cache-control'),'private, no-store');
assert.equal(response.headers.get('x-content-type-options'),'nosniff');
const bytes=await response.arrayBuffer();const sha256=createHash('sha256').update(new Uint8Array(bytes)).digest('hex');
assert.equal(sha256,proof.pdf.sha256);assert.equal(bytes.byteLength,proof.pdf.size);
assert.equal(response.headers.get('etag'),`"${sha256}"`);
const attachment=await fetch(url+'?download=1',{headers:{Cookie:`__convexAuthJWT=${session.token}; __convexAuthRefreshToken=${session.refreshToken}`}});
assert.equal(attachment.status,200);assert.match(attachment.headers.get('content-disposition'),/^attachment;/);
assert.equal(createHash('sha256').update(new Uint8Array(await attachment.arrayBuffer())).digest('hex'),sha256);
const client=new ConvexHttpClient(run.url);client.setAuth(session.token);
const availability=await client.query('quotationRevisionUi:availability',{});
const command=JSON.parse(await fs.readFile(`${runDir}/http-command.json`,'utf8'));
const replay=await fetch('http://localhost:3540/api/quotations/create',{method:'POST',headers:{'Content-Type':'application/json',Cookie:`__convexAuthJWT=${session.token}; __convexAuthRefreshToken=${session.refreshToken}`},body:JSON.stringify({command,expected_actor:availability.actor})});
assert.equal(replay.status,200);const replayed=await replay.json();assert.equal(replayed.id,proof.pdf.revisionId);
const oldFlat=await fetch('http://localhost:3540/api/quotations/create',{method:'POST',headers:{'Content-Type':'application/json',Cookie:`__convexAuthJWT=${session.token}; __convexAuthRefreshToken=${session.refreshToken}`},body:'{}'});assert.equal(oldFlat.status,409);
const result={httpReplayExactId:replayed.id,oldFlatAfterFreeze:oldFlat.status,source,sourceCommit:run.sourceCommit,webUrl:'http://localhost:3540',browserConvexUrl:run.url,serverConvexUrl:run.url,pdfUrl:url,anonymousStatus:anonymous.status,authenticatedStatus:response.status,sha256,size:bytes.byteLength,attachmentSameBytes:true,scope:'Real HTTP application route with actual password JWT cookie. Browser login is a separate journey.'};
await fs.writeFile(`${runDir}/http-proof.json`,JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
